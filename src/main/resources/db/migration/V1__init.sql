CREATE TABLE users (
                       id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username   VARCHAR(255) NOT NULL UNIQUE,
                       email      VARCHAR(255) NOT NULL UNIQUE,
                       password   VARCHAR(255) NOT NULL,
                       role       VARCHAR(255) NOT NULL,
                       created_at TIMESTAMP
);

CREATE TABLE exercises (
                           id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name         VARCHAR(255) NOT NULL,
                           muscle_group VARCHAR(255) NOT NULL,
                           equipment    VARCHAR(255),
                           description  VARCHAR(255),
                           video_url    VARCHAR(255),
                           image_url    VARCHAR(255)
);

CREATE TABLE workouts (
                          id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name    VARCHAR(255) NOT NULL,
                          date    DATE NOT NULL,
                          user_id BIGINT NOT NULL REFERENCES users (id)
);

CREATE TABLE workout_exercises (
                                   id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   workout_id  BIGINT NOT NULL REFERENCES workouts (id),
                                   exercise_id BIGINT NOT NULL REFERENCES exercises (id),
                                   order_index INTEGER NOT NULL,
                                   CONSTRAINT uq_workout_order UNIQUE (workout_id, order_index)
);

CREATE TABLE workout_sets (
                              id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              workout_exercise_id BIGINT NOT NULL REFERENCES workout_exercises (id),
                              set_number          INTEGER NOT NULL,
                              reps_done           INTEGER NOT NULL,
                              weight              NUMERIC(38, 2) NOT NULL
);